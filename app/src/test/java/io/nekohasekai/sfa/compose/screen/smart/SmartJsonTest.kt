    @Test
    fun parsesCoreNetworkHistoryAndEmptyHistory() {
        val networks = SmartJson.networks(fixture("networks.json"))

        assertEquals(1, networks.version)
        assertEquals(listOf("cell", "cell/25001", "cell/25001/LTE"), networks.networks.map { it.key })
        val network = networks.networks.last()
        assertEquals("cellular", network.type)
        assertEquals("Fixture Carrier LTE", network.label)
        assertEquals("Fixture Carrier", network.carrier)
        assertEquals("LTE", network.radio)
        assertEquals(1_800_000_000L, network.lastSeen)
        assertEquals(1.0, network.weight, 0.0)
        assertEquals(2, network.members.size)
        val primary = network.members.first()
        assertEquals("a", primary.tag)
        assertEquals(1.0, primary.weight, 0.0)
        assertEquals(48.1, primary.downloadMbps!!, 0.0)
        assertEquals(120.0, primary.rttMs!!, 0.0)
        assertNull(network.members[1].downloadMbps)
        assertNull(network.members[1].rttMs)
        assertTrue(SmartJson.networks(fixture("networks-empty.json")).networks.isEmpty())
    }

    @Test
    fun parsesCoreImportReportsIncludingReplacementAndEmptyResults() {
        val report = SmartJson.importReport(fixture("import-report.json"))

        assertEquals(1, report.version)
        assertEquals("android-fixture-source", report.sourceInstallId)
        assertEquals(0.25, report.trust, 0.0)
        assertFalse(report.replacedPreviousImport)
        assertEquals(listOf("cell", "cell/25001", "cell/25001/LTE"), report.applied.map { it.network })
        for (applied in report.applied) {
            assertEquals(applied.network, applied.mappedTo)
            assertEquals(1, applied.members)
            assertEquals(0.25, applied.weight, 0.0)
        }
        assertEquals(
            setOf(
                SmartImportIgnored("wifi/bssid:0123456789abcdef", "foreign_redacted_key"),
                SmartImportIgnored("other", "unknown_member"),
            ),
            report.ignored.toSet(),
        )
        assertTrue(SmartJson.importReport(fixture("import-report-replaced.json")).replacedPreviousImport)
        val empty = SmartJson.importReport(fixture("import-report-empty.json"))
        assertTrue(empty.applied.isEmpty())
        assertTrue(empty.ignored.isEmpty())
    }

    @Test
    fun readsCoreExportMetadataAndFillsMissingPlatformFieldsWithoutChangingHistory() {
        val exported = fixture("export.json")
        val metadata = SmartJson.exportMetadata(exported)
        assertEquals(1, metadata.version)
        assertEquals(1_800_000_000L, metadata.exportedAt)
        assertEquals("android-fixture-install", metadata.installId)
        assertTrue(metadata.redacted)
        assertNull(metadata.model)
        assertEquals(setOf("Fixture Carrier"), metadata.carriers)
        assertEquals(0.25, SmartJson.importTrust(exported, "Pixel 9", "Fixture Carrier"), 0.0)

        val stamped = SmartJson.exportWithDevice(exported, " Pixel 9 ", " 16 ", " SFA Smart ")
        val device = requireNotNull(SmartJson.exportMetadata(stamped).device)
        assertEquals("Pixel 9", device.model)
        assertEquals("16", device.android)
        assertEquals("SFA Smart", device.app)
        val originalObject = Json.parseToJsonElement(exported).jsonObject
        val stampedObject = Json.parseToJsonElement(stamped).jsonObject
        assertEquals(originalObject - "device", stampedObject - "device")
        assertEquals(stampedObject, Json.parseToJsonElement(SmartJson.exportWithDevice(stamped, "Other", "Other", "Other")))
    }

    @Test
    fun computesImportTrustOnlyFromNonemptyModelAndCarrierMatches() {
        val exported = SmartJson.exportWithDevice(fixture("export.json"), "Pixel 9", "16", "SFA Smart")
        val cases =
            listOf(
                Triple("Pixel 9", "Fixture Carrier", 0.5),
                Triple(" pixel 9 ", " fixture carrier ", 0.5),
                Triple("Other", "Fixture Carrier", 0.25),
                Triple("", "Fixture Carrier", 0.25),
                Triple("   ", "Fixture Carrier", 0.25),
                Triple("Pixel 9", "Other", 0.1),
                Triple("Pixel 9", "", 0.1),
                Triple("Pixel 9", "   ", 0.1),
                Triple("", "", 0.1),
            )
        for ((model, carrier, expected) in cases) {
            assertEquals("$model / $carrier", expected, SmartJson.importTrust(exported, model, carrier), 0.0)
        }
    }

    @Test
    fun missingOrBlankExportMetadataNeverCreatesAMatch() {
        val original = Json.parseToJsonElement(fixture("export.json")).jsonObject
        for (device in listOf(null, JsonNull, JsonObject(emptyMap()))) {
            val data = JsonObject((original - "device") + if (device == null) emptyMap() else mapOf("device" to device)).toString()
            assertEquals(0.25, SmartJson.importTrust(data, "", "Fixture Carrier"), 0.0)
            assertEquals("Pixel 9", SmartJson.exportMetadata(SmartJson.exportWithDevice(data, "Pixel 9", "16", "SFA Smart")).model)
        }
        val stamped = SmartJson.exportWithDevice(original.toString(), "Pixel 9", "16", "SFA Smart")
        val root = Json.parseToJsonElement(stamped).jsonObject
        for (carrier in listOf(null, JsonNull, JsonPrimitive(""), JsonPrimitive("   "))) {
            val groups =
                root.getValue("groups").jsonObject.mapValues { (_, groupElement) ->
                    val group = groupElement.jsonObject
                    val networks =
                        group.getValue("networks").jsonObject.mapValues { (_, networkElement) ->
                            val network = networkElement.jsonObject
                            JsonObject((network - "carrier") + if (carrier == null) emptyMap() else mapOf("carrier" to carrier))
                        }
                    JsonObject(group + ("networks" to JsonObject(networks)))
                }
            val data = JsonObject(root + ("groups" to JsonObject(groups))).toString()
            assertTrue(SmartJson.exportMetadata(data).carriers.isEmpty())
            assertEquals(0.1, SmartJson.importTrust(data, "Pixel 9", ""), 0.0)
            assertEquals(0.1, SmartJson.importTrust(data, "Pixel 9", "Fixture Carrier"), 0.0)
        }
        assertEquals(0.1, SmartJson.importTrust(JsonObject(root + ("groups" to JsonObject(emptyMap()))).toString(), "Pixel 9", "Fixture Carrier"), 0.0)
    }

    @Test
    fun rejectsUnsupportedDocumentVersions() {
        val cases =
            listOf<Pair<String, (String) -> Any>>(
                "status.json" to SmartJson::status,
                "networks.json" to SmartJson::networks,
                "import-report.json" to SmartJson::importReport,
                "export.json" to SmartJson::exportMetadata,
            )
        for ((name, parse) in cases) {
            val root = Json.parseToJsonElement(fixture(name)).jsonObject
            val unsupported = JsonObject(root + ("version" to JsonPrimitive(2))).toString()
            try {
                parse(unsupported)
                fail("Accepted unsupported version in $name")
            } catch (error: IllegalArgumentException) {
                assertEquals("unsupported_version", error.message)
            }
        }
    }

    private fun fixture(name: String): String = requireNotNull(javaClass.getResourceAsStream("/smart/$name")) {
        "Missing core-generated fixture: $name"
    }.bufferedReader().use { it.readText() }
}
